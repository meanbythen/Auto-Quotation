def current() -> str:
    return __version__


def version_text() -> str:
    return f"v{__version__} · {VERSION_TAG}"


def find(version: str) -> dict | None:
    for item in CHANGELOG:
        if item["version"] == version:
            return item
    return None


def latest() -> dict:
    return CHANGELOG[0]


def recent_changes(count: int = 3) -> list[str]:
    """最近 N 条变更点（启动日志用）"""
    out: list[str] = []
    for item in CHANGELOG:
        for c in item["changes"]:
            out.append(f"[{item['version']}] {c}")
            if len(out) >= count:
                return out
    return out


def format_changelog_markdown() -> str:
    lines = [f"# {APP_NAME} 更新日志", ""]
    lines.append(f"当前版本：**v{__version__}**（{VERSION_TAG}）")
    lines.append("")
    for item in CHANGELOG:
        lines.append(f"## v{item['version']} · {item['date']} · {item['title']}")
        lines.append("")
        for c in item["changes"]:
            lines.append(f"- {c}")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def write_changelog_md(path: str | Path | None = None) -> Path:
    if path is None:
        if getattr(sys, "frozen", False):
            path = Path(sys.executable).resolve().parent / "CHANGELOG.md"
        else:
            path = Path(__file__).resolve().parent.parent / "CHANGELOG.md"
    path = Path(path)
    path.write_text(format_changelog_markdown(), encoding="utf-8")
    return path


if __name__ == "__main__":
    if "--write" in sys.argv:
        p = write_changelog_md()
        print(f"已写入 {p}")
    else:
        print(format_changelog_markdown())

